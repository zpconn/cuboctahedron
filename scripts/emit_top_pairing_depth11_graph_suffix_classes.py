#!/usr/bin/env python3
"""Emit lightweight depth-11 graph suffix class predicates.

The older closed-provider module bundled these predicates with final-margin
socket conversions, which makes it unsuitable as a lightweight import for the
mapped layer-4 Bellman route.  This script emits just the class predicates from
the graph-state suffix smoke.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path


DEFAULT_SUFFIX_INPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphStateSuffixSmoke.lean"
)
DEFAULT_OUTPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphSuffixClasses.lean"
)

INDUCTIVE_RE = re.compile(
    r"^inductive Depth11Class(?P<class>\d{3})State(?P<state>\d{4})Suffix\b"
)


def parse_classes(path: Path) -> dict[str, list[str]]:
    classes: dict[str, set[str]] = defaultdict(set)
    for line in path.read_text(encoding="utf-8").splitlines():
        if match := INDUCTIVE_RE.match(line):
            classes[match.group("class")].add(match.group("state"))
    if not classes:
        raise ValueError(f"no depth-11 graph-state suffix classes found in {path}")
    return {
        class_id: sorted(states, key=int)
        for class_id, states in sorted(classes.items(), key=lambda item: int(item[0]))
    }


def emit_class(class_id: str, states: list[str]) -> list[str]:
    lines = [
        f"/-- Lightweight depth-11 graph-state suffix alternatives for class {class_id}. -/",
        f"def Class{class_id}Depth11Suffix (graph : State) (rest : List Face) : Prop :=",
    ]
    for index, state in enumerate(states):
        prefix = "  " if index == 0 else "    "
        suffix = " ∨" if index + 1 < len(states) else ""
        lines.append(
            f"{prefix}(graph = ({int(state)} : State) ∧ "
            f"Depth11Class{class_id}State{state}Suffix rest){suffix}"
        )
    return lines


def emit_module(classes: dict[str, list[str]]) -> str:
    lines = [
        "import Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphStateSuffixSmoke",
        "",
        "/-!",
        "Lightweight depth-11 graph suffix class predicates.",
        "",
        "This module is generated by",
        "`scripts/emit_top_pairing_depth11_graph_suffix_classes.py`.  It splits",
        "the semantic suffix class predicates away from the old closed/final-margin",
        "provider socket so downstream Bellman graph-eval modules can avoid stale",
        "terminal trace imports.",
        "-/",
        "",
        "namespace Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixClasses",
        "",
        "open Cuboctahedron",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingGraphEvalSplit10MSmoke.Base",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphStateSuffixSmoke",
        "",
    ]
    for class_id, states in classes.items():
        lines.extend(emit_class(class_id, states))
        lines.append("")
    lines.extend(
        [
            "theorem depth11GraphSuffixClasses_builds : True := by",
            "  exact True.intro",
            "",
            "end Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixClasses",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--suffix-input", type=Path, default=DEFAULT_SUFFIX_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    classes = parse_classes(args.suffix_input)
    args.output.write_text(emit_module(classes), encoding="utf-8")
    print(
        f"wrote {args.output} with {len(classes)} classes: "
        + ", ".join(classes)
    )


if __name__ == "__main__":
    main()
