#!/usr/bin/env python3
"""Emit trace-free depth-11 graph-state suffix predicates.

The historical depth-11 suffix smoke module also proves branch-table suffix
facts, which imports the old trace-classifier path.  The mapped Bellman finish
route only needs the small `Depth11ClassNNNStateSSSSSuffix` inductive
predicates.  This emitter extracts exactly those predicates into a lightweight
core module.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


DEFAULT_INPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphStateSuffixSmoke.lean"
)
DEFAULT_OUTPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphStateSuffixCore.lean"
)

INDUCTIVE_START_RE = re.compile(r"^inductive Depth11Class\d{3}State\d{4}Suffix\b")
INDUCTIVE_BODY_RE = re.compile(r"^\s*\|\s+\w+\s*:")


def extract_suffix_core(path: Path) -> tuple[list[str], int, int]:
    lines = path.read_text(encoding="utf-8").splitlines()
    count_defs: list[str] = []
    suffix_blocks: list[str] = []
    obligation_count = 0
    provider_count = 0
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("def depth11GraphStateSuffixObligationCount"):
            count_defs.append(line)
            obligation_count = int(line.rsplit(":=", 1)[1].strip())
            index += 1
            continue
        if line.startswith("def depth11GraphStateSuffixProviderCount"):
            count_defs.append(line)
            provider_count = int(line.rsplit(":=", 1)[1].strip())
            index += 1
            continue
        if INDUCTIVE_START_RE.match(line):
            block = [line]
            index += 1
            while index < len(lines) and INDUCTIVE_BODY_RE.match(lines[index]):
                block.append(lines[index])
                index += 1
            suffix_blocks.append("\n".join(block))
            continue
        index += 1
    if not suffix_blocks:
        raise ValueError(f"no depth-11 suffix inductives found in {path}")
    if not count_defs:
        raise ValueError(f"no depth-11 suffix count definitions found in {path}")
    return count_defs + suffix_blocks, obligation_count, provider_count


def emit_module(blocks: list[str], obligation_count: int, provider_count: int) -> str:
    lines = [
        "import Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingGraphEvalSplit10MSmoke.Base",
        "",
        "/-!",
        "Trace-free depth-11 graph-state suffix predicates.",
        "",
        "This module is generated by",
        "`scripts/emit_top_pairing_depth11_graph_state_suffix_core.py`.  It",
        "contains only the lightweight suffix `Prop` alternatives needed by the",
        "direct mapped Bellman finish route.  It intentionally avoids the old",
        "branch-table suffix and terminal trace-classifier imports.",
        "-/",
        "",
        "namespace Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphStateSuffixCore",
        "",
        "open Cuboctahedron",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingGraphEvalSplit10MSmoke.Base",
        "",
    ]
    for block in blocks:
        lines.append(block)
        lines.append("")
    lines.extend(
        [
            "theorem depth11GraphStateSuffixCoreCount_audit :",
            f"    depth11GraphStateSuffixObligationCount = {obligation_count} /\\",
            f"      depth11GraphStateSuffixProviderCount = {provider_count} := by",
            "  decide",
            "",
            "theorem depth11GraphStateSuffixCore_builds : True := by",
            "  exact True.intro",
            "",
            "end Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphStateSuffixCore",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    blocks, obligation_count, provider_count = extract_suffix_core(args.input)
    args.output.write_text(
        emit_module(blocks, obligation_count, provider_count),
        encoding="utf-8",
    )
    print(
        f"wrote {args.output} with {provider_count} providers "
        f"and {obligation_count} obligations"
    )


if __name__ == "__main__":
    main()
