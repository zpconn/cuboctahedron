#!/usr/bin/env python3
"""Emit lightweight depth-11 graph suffix producer predicates."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


DEFAULT_CLASSES_INPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphSuffixClasses.lean"
)
DEFAULT_OUTPUT = Path(
    "Cuboctahedron/Generated/NonIdentity/Residual/"
    "BellmanTopPairingDepth11GraphSuffixProducers.lean"
)

CLASS_RE = re.compile(r"^def Class(?P<class>\d{3})Depth11Suffix\b")


def parse_classes(path: Path) -> list[str]:
    classes: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if match := CLASS_RE.match(line):
            classes.append(match.group("class"))
    if not classes:
        raise ValueError(f"no ClassNNNDepth11Suffix definitions found in {path}")
    return sorted(set(classes), key=int)


def emit_class(class_id: str) -> list[str]:
    return [
        f"/-- Lightweight graph-suffix producer predicate for class {class_id}. -/",
        f"def Class{class_id}GraphSuffixProducer (rank : Fin numPairWords) : Prop :=",
        "  ∀ face₀ face₁ rest,",
        "    topPairingRankFaceLabels rank =",
        "      Face.xm :: Face.ym :: face₀ :: face₁ :: rest ->",
        "    Depth11Layer4SemanticFrontierBranch face₀ face₁ ->",
        "    ∀ graph₁ gain₁ graph₂ gain₂,",
        "      graphSmokeNext (610 : State) (smokeLabelOfFace face₀) =",
        "        some (graph₁, gain₁) ->",
        "      graphSmokeNext graph₁ (smokeLabelOfFace face₁) =",
        "        some (graph₂, gain₂) ->",
        f"      Class{class_id}Depth11Suffix graph₂ rest",
        "",
    ]


def emit_module(classes: list[str]) -> str:
    lines = [
        "import Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixClasses",
        "import Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11Layer4ClassifierSocket",
        "",
        "/-!",
        "Lightweight depth-11 graph suffix producer predicates.",
        "",
        "This module is generated by",
        "`scripts/emit_top_pairing_depth11_graph_suffix_producers.py`.  It splits",
        "the semantic graph-suffix producer predicates away from the old",
        "closed/final-margin provider socket.  The producer accepts the seven-way",
        "layer-4 semantic frontier already proved from the closed language.",
        "-/",
        "",
        "namespace Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixProducers",
        "",
        "open Cuboctahedron",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingGraphEvalSplit10MSmoke.Base",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixClasses",
        "open Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11Layer4ClassifierSocket",
        "",
    ]
    for class_id in classes:
        lines.extend(emit_class(class_id))
    lines.extend(
        [
            "theorem depth11GraphSuffixProducers_builds : True := by",
            "  exact True.intro",
            "",
            "end Cuboctahedron.Generated.NonIdentity.Residual.BellmanTopPairingDepth11GraphSuffixProducers",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--classes-input", type=Path, default=DEFAULT_CLASSES_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    classes = parse_classes(args.classes_input)
    args.output.write_text(emit_module(classes), encoding="utf-8")
    print(
        f"wrote {args.output} with {len(classes)} classes: "
        + ", ".join(classes)
    )


if __name__ == "__main__":
    main()
